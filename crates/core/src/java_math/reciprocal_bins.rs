pub(super) fn quantized(packed: u32) -> u32 {
    assert_eq!(packed & 0xff80_0000, 0x3f80_0000);
    let mantissa = packed & 0x007f_ffff;
    let passed = TRANSITION_STARTS.partition_point(|&start| start <= mantissa);
    let bin = 512 - passed as u32;
    0x3f39_0000 + (bin << 14)
}
